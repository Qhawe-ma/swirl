import { useState } from 'react';
import { useWallet, useConnection } from '@solana/wallet-adapter-react';
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Textarea } from "@/components/ui/textarea";
import { Card } from "@/components/ui/card";
import { Alert, AlertDescription } from "@/components/ui/alert";
import { useToast } from "@/hooks/use-toast";
import { uploadToIPFS } from "@/lib/ipfs";
import { mintNFT } from "@/lib/solana";
import { saveMintRecord } from "@/lib/firebase";

interface NFTMintingFormProps {
  imageData: string;
  onMintSuccess: (mintAddress: string) => void;
  onMintStart: () => void;
}

export function NFTMintingForm({ imageData, onMintSuccess, onMintStart }: NFTMintingFormProps) {
  const [nftName, setNftName] = useState('');
  const [nftDescription, setNftDescription] = useState('');
  const [isLoading, setIsLoading] = useState(false);
  const { connected, publicKey, signTransaction } = useWallet();
  const { connection } = useConnection();
  const { toast } = useToast();

  const dataURLtoBlob = (dataurl: string): Blob => {
    const arr = dataurl.split(',');
    const mime = arr[0].match(/:(.*?);/)![1];
    const bstr = atob(arr[1]);
    let n = bstr.length;
    const u8arr = new Uint8Array(n);
    while(n--) {
      u8arr[n] = bstr.charCodeAt(n);
    }
    return new Blob([u8arr], {type: mime});
  };

  const handleMintNFT = async () => {
    if (!connected || !publicKey) {
      toast({
        title: "Wallet not connected",
        description: "Please connect your wallet first.",
        variant: "destructive",
      });
      return;
    }

    if (!nftName.trim()) {
      toast({
        title: "Name required",
        description: "Please enter a name for your NFT.",
        variant: "destructive",
      });
      return;
    }

    setIsLoading(true);
    onMintStart();

    try {
      console.log('🎨 Starting NFT minting process...');
      
      // Convert base64 to blob
      const imageBlob = dataURLtoBlob(imageData);
      console.log('✅ Image blob created, size:', imageBlob.size);
      
      // Upload image to IPFS
      console.log('📤 Uploading image to IPFS...');
      try {
        const imageUri = await uploadToIPFS(imageBlob, 'image');
        console.log('✅ Image uploaded to:', imageUri);
        
        // Create metadata
        const metadata = {
          name: nftName.trim(),
          description: nftDescription.trim() || '',
          image: imageUri,
          attributes: [
            {
              trait_type: 'Generated By',
              value: 'Paint NFT'
            }
          ],
          properties: {
            files: [
              {
                uri: imageUri,
                type: 'image/png'
              }
            ]
          }
        };
        
        // Upload metadata to IPFS
        console.log('📤 Uploading metadata to IPFS...');
        const metadataBlob = new Blob([JSON.stringify(metadata)], { type: 'application/json' });
        const metadataUri = await uploadToIPFS(metadataBlob, 'metadata');
        console.log('✅ Metadata uploaded to:', metadataUri);
        
        // Update UI to show wallet confirmation step
        toast({
          title: "Ready to Mint!",
          description: "Please confirm the transaction in your wallet to mint on Solana mainnet.",
        });
        
        // Mint NFT on mainnet - this will require wallet signature and SOL fees
        console.log('🚀 Requesting wallet signature for Solana mainnet minting...');
        const walletAdapter = { publicKey, signTransaction };
        const mintResult = await mintNFT(
          connection,
          walletAdapter,
          metadataUri,
          nftName.trim()
        );
        console.log('🎉 NFT minted with address:', mintResult.mintAddress);
        
        // Save mint record to Firebase
        console.log('💾 Saving mint record to Firebase...');
        try {
          await saveMintRecord({
            walletAddress: publicKey.toBase58(),
            mintAddress: mintResult.mintAddress,
            name: nftName.trim(),
            imageData: imageData,
            metadataUri: metadataUri,
            transactionSignature: mintResult.transactionSignature
          });
          console.log('✅ Mint record saved to Firebase');
        } catch (firebaseError) {
          console.error('⚠️ Failed to save to Firebase (NFT still minted):', firebaseError);
        }
        
        onMintSuccess(mintResult.mintAddress);
        
        toast({
          title: "NFT Minted Successfully!",
          description: `Your artwork is now a real NFT on Solana mainnet! Address: ${mintResult.mintAddress}`,
        });
        
      } catch (ipfsError: any) {
        console.error('❌ Unexpected error during minting:', ipfsError);
        throw ipfsError; // Re-throw to be caught by outer catch block
      }
      
    } catch (error: any) {
      console.error('Minting error:', error);
      
      // Provide more helpful error messages based on the error type
      let errorTitle = "Minting Failed";
      let errorDescription = "Failed to mint NFT. Please try again.";
      
      if (error.message?.includes('timeout') || error.message?.includes('timed out')) {
        errorTitle = "Transaction Timeout";
        errorDescription = "Transaction took too long to confirm. Check Solana Explorer with the transaction signature to see if it succeeded. If not, try again with more SOL for fees.";
      } else if (error.message?.includes('insufficient funds') || error.message?.includes('SOL')) {
        errorTitle = "Insufficient SOL";
        errorDescription = "You need more SOL in your wallet for transaction fees. Add at least 0.01 SOL and try again.";
      } else if (error.message?.includes('signature')) {
        errorTitle = "Transaction Issue";
        errorDescription = `${error.message}`;
      } else if (error.message?.includes('rejected') || error.message?.includes('cancelled')) {
        errorTitle = "Transaction Cancelled";
        errorDescription = "Transaction was cancelled in your wallet. Please try again and approve the transaction.";
      } else {
        errorDescription = error.message || "Unknown error occurred. Please try again.";
      }
      
      toast({
        title: errorTitle,
        description: errorDescription,
        variant: "destructive",
      });
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <div className="flex justify-center items-center min-h-0 bg-gradient-to-br from-muted/20 via-transparent to-muted/30 p-6">
      <Card className="bg-card/90 backdrop-blur-xl border border-border/50 max-w-4xl w-full shadow-2xl" data-testid="form-nft-minting">
        {/* Modern Header */}
        <div className="bg-gradient-to-r from-primary/10 via-primary/5 to-transparent border-b border-border/30 px-6 py-4">
          <h2 className="text-lg font-semibold text-foreground flex items-center tracking-wide">
            <span className="mr-3 text-xl">💎</span>
            Mint as NFT
          </h2>
        </div>

        <div className="p-6">
          <div className="flex gap-8">
            {/* Modern Artwork Preview */}
            <div className="w-64 flex-shrink-0">
              <h3 className="text-sm font-medium text-muted-foreground uppercase tracking-wider mb-3">Your Artwork</h3>
              <div className="bg-card border border-border/50 rounded-xl p-4 shadow-lg">
                <img 
                  src={imageData} 
                  alt="User artwork preview" 
                  className="w-full rounded-lg border border-border/30 shadow-sm"
                  data-testid="img-artwork-preview"
                />
              </div>
            </div>
            
            {/* Modern NFT Details Form */}
            <div className="flex-1">
              <div className="space-y-6">
                <div className="space-y-2">
                  <label htmlFor="nft-name" className="text-sm font-medium text-foreground">NFT Name *</label>
                  <Input
                    id="nft-name"
                    type="text" 
                    placeholder="e.g., Abstract Dreams #1" 
                    value={nftName}
                    onChange={(e) => setNftName(e.target.value)}
                    disabled={isLoading}
                    className="text-base focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2"
                    data-testid="input-nft-name"
                  />
                </div>
                
                <div className="space-y-2">
                  <label htmlFor="nft-description" className="text-sm font-medium text-foreground">Description</label>
                  <Textarea
                    id="nft-description"
                    placeholder="Describe your artwork..." 
                    rows={4} 
                    value={nftDescription}
                    onChange={(e) => setNftDescription(e.target.value)}
                    disabled={isLoading}
                    className="resize-none text-base focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2"
                    data-testid="textarea-nft-description"
                  />
                </div>
                
                {/* Modern Cost Info Alert */}
                <Alert className="border-amber-200 bg-amber-50 dark:border-amber-800 dark:bg-amber-950">
                  <span className="text-lg">⚠️</span>
                  <AlertDescription className="text-amber-800 dark:text-amber-200">
                    <div className="font-semibold mb-1">Mainnet Minting Cost</div>
                    <div className="text-sm">
                      Estimated: ~0.002-0.01 SOL for transaction fees<br/>
                      Please ensure sufficient SOL in your wallet
                    </div>
                  </AlertDescription>
                </Alert>
              </div>
            </div>
          </div>
          
          {/* Modern Mint Button */}
          <div className="mt-8 flex justify-center">
            <Button
              size="lg"
              className={`px-8 py-4 text-base font-semibold bg-gradient-to-r from-primary to-primary/90 hover:from-primary/90 hover:to-primary/80 text-primary-foreground shadow-lg hover:shadow-xl transition-all duration-300 motion-safe:hover:scale-105 focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 ${
                isLoading || !connected ? 'opacity-50 cursor-not-allowed' : ''
              }`}
              onClick={handleMintNFT}
              disabled={isLoading || !connected}
              data-testid="button-mint-nft"
            >
              <span className="mr-2 text-lg">💎</span>
              {isLoading ? 'Minting...' : 'Mint NFT on Solana'}
            </Button>
          </div>
        </div>
      </Card>
    </div>
  );
}