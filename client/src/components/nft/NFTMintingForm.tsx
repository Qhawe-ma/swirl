import { useState } from 'react';
import { useWallet, useConnection } from '@solana/wallet-adapter-react';
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Textarea } from "@/components/ui/textarea";
import { Card } from "@/components/ui/card";
import { Alert, AlertDescription } from "@/components/ui/alert";
import { useToast } from "@/hooks/use-toast";
import { uploadToIPFS } from "@/lib/ipfs";
import { mintNFT } from "@/lib/solana";

interface NFTMintingFormProps {
  imageData: string;
  onMintSuccess: (mintAddress: string) => void;
  onMintStart: () => void;
}

export function NFTMintingForm({ imageData, onMintSuccess, onMintStart }: NFTMintingFormProps) {
  const [nftName, setNftName] = useState('');
  const [nftDescription, setNftDescription] = useState('');
  const [isLoading, setIsLoading] = useState(false);
  const { connected, publicKey } = useWallet();
  const { connection } = useConnection();
  const { toast } = useToast();

  const dataURLtoBlob = (dataurl: string): Blob => {
    const arr = dataurl.split(',');
    const mime = arr[0].match(/:(.*?);/)![1];
    const bstr = atob(arr[1]);
    let n = bstr.length;
    const u8arr = new Uint8Array(n);
    while(n--) {
      u8arr[n] = bstr.charCodeAt(n);
    }
    return new Blob([u8arr], {type: mime});
  };

  const handleMintNFT = async () => {
    if (!connected || !publicKey) {
      toast({
        title: "Wallet not connected",
        description: "Please connect your wallet first.",
        variant: "destructive",
      });
      return;
    }

    if (!nftName.trim()) {
      toast({
        title: "Name required",
        description: "Please enter a name for your NFT.",
        variant: "destructive",
      });
      return;
    }

    setIsLoading(true);
    onMintStart();

    try {
      // Convert base64 to blob
      const imageBlob = dataURLtoBlob(imageData);
      
      // Upload image to IPFS
      const imageUri = await uploadToIPFS(imageBlob, 'image');
      
      // Create metadata
      const metadata = {
        name: nftName.trim(),
        description: nftDescription.trim() || '',
        image: imageUri,
        attributes: [
          {
            trait_type: 'Generated By',
            value: 'Solana Paint App'
          }
        ],
        properties: {
          files: [
            {
              uri: imageUri,
              type: 'image/png'
            }
          ]
        }
      };
      
      // Upload metadata to IPFS
      const metadataBlob = new Blob([JSON.stringify(metadata)], { type: 'application/json' });
      const metadataUri = await uploadToIPFS(metadataBlob, 'metadata');
      
      // Mint NFT
      const mintAddress = await mintNFT(
        connection,
        publicKey,
        metadataUri,
        nftName.trim()
      );
      
      onMintSuccess(mintAddress);
      
      toast({
        title: "NFT Minted Successfully!",
        description: `Your artwork is now an NFT on Solana mainnet.`,
      });
      
    } catch (error: any) {
      console.error('Minting error:', error);
      toast({
        title: "Minting Failed",
        description: error.message || "Failed to mint NFT. Please try again.",
        variant: "destructive",
      });
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <Card className="p-6" data-testid="form-nft-minting">
      <h2 className="text-lg font-medium text-gray-900 mb-6 flex items-center">
        <span className="material-icons mr-2">token</span>
        Mint as NFT
      </h2>
      
      <div className="grid md:grid-cols-2 gap-8">
        {/* Artwork Preview */}
        <div>
          <h3 className="text-sm font-medium text-gray-700 mb-3">Your Artwork</h3>
          <div className="nft-preview p-4 rounded-lg border-2 border-dashed border-gray-300">
            <img 
              src={imageData} 
              alt="User artwork preview" 
              className="w-full rounded-lg shadow-sm"
              data-testid="img-artwork-preview"
            />
          </div>
        </div>
        
        {/* NFT Details Form */}
        <div>
          <div className="space-y-4">
            <div>
              <label className="block text-sm font-medium text-gray-700 mb-2">NFT Name *</label>
              <Input 
                type="text" 
                placeholder="e.g., Abstract Dreams #1" 
                value={nftName}
                onChange={(e) => setNftName(e.target.value)}
                disabled={isLoading}
                data-testid="input-nft-name"
              />
            </div>
            
            <div>
              <label className="block text-sm font-medium text-gray-700 mb-2">Description</label>
              <Textarea 
                placeholder="Describe your artwork..." 
                rows={4} 
                value={nftDescription}
                onChange={(e) => setNftDescription(e.target.value)}
                disabled={isLoading}
                className="resize-none"
                data-testid="textarea-nft-description"
              />
            </div>
            
            {/* Minting Cost Info */}
            <Alert className="border-yellow-200 bg-yellow-50">
              <span className="material-icons text-yellow-600 text-sm">warning</span>
              <AlertDescription className="text-sm">
                <div className="font-medium text-yellow-800">Mainnet Minting Cost</div>
                <div className="text-yellow-700 mt-1">
                  Estimated: ~0.002-0.01 SOL for transaction fees<br/>
                  Ensure you have sufficient SOL in your wallet
                </div>
              </AlertDescription>
            </Alert>
            
            {/* Mint Button */}
            <Button 
              className="w-full bg-success hover:bg-green-600 text-white p-3 font-medium" 
              onClick={handleMintNFT}
              disabled={isLoading || !connected}
              data-testid="button-mint-nft"
            >
              <span className="material-icons text-sm mr-2">token</span>
              <span>{isLoading ? 'Minting...' : 'Mint NFT on Solana'}</span>
            </Button>
          </div>
        </div>
      </div>
    </Card>
  );
}
